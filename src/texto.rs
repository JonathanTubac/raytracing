//! On-screen text with a handmade 5 x 7 pixel font, for the video captions

use crate::framebuffer::Framebuffer;

const ANCHO: usize = 5;
const ALTO: usize = 7;

fn glifo(c: char) -> [u8; ALTO] {
    match c.to_ascii_uppercase() {
        'A' => [0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11],
        'B' => [0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E],
        'C' => [0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E],
        'D' => [0x1E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1E],
        'E' => [0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F],
        'F' => [0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10],
        'G' => [0x0E, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0F],
        'H' => [0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11],
        'I' => [0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E],
        'J' => [0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0C],
        'K' => [0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11],
        'L' => [0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F],
        'M' => [0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11],
        'N' => [0x11, 0x11, 0x19, 0x15, 0x13, 0x11, 0x11],
        'O' => [0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E],
        'P' => [0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10],
        'Q' => [0x0E, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0D],
        'R' => [0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11],
        'S' => [0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E],
        'T' => [0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04],
        'U' => [0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E],
        'V' => [0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04],
        'W' => [0x11, 0x11, 0x11, 0x15, 0x15, 0x15, 0x0A],
        'X' => [0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11],
        'Y' => [0x11, 0x11, 0x11, 0x0A, 0x04, 0x04, 0x04],
        'Z' => [0x1F, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1F],
        '0' => [0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E],
        '1' => [0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E],
        '2' => [0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F],
        '3' => [0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E],
        '4' => [0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02],
        '5' => [0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E],
        '6' => [0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E],
        '7' => [0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08],
        '8' => [0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E],
        '9' => [0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C],
        ':' => [0x00, 0x0C, 0x0C, 0x00, 0x0C, 0x0C, 0x00],
        '-' => [0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00],
        '.' => [0x00, 0x00, 0x00, 0x00, 0x00, 0x0C, 0x0C],
        ',' => [0x00, 0x00, 0x00, 0x00, 0x0C, 0x04, 0x08],
        '/' => [0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x00],
        '(' => [0x02, 0x04, 0x08, 0x08, 0x08, 0x04, 0x02],
        ')' => [0x08, 0x04, 0x02, 0x02, 0x02, 0x04, 0x08],
        '+' => [0x00, 0x04, 0x04, 0x1F, 0x04, 0x04, 0x00],
        _ => [0; ALTO],
    }
}

/// Width in pixels of the text at that scale
pub fn ancho(texto: &str, escala: usize) -> usize {
    texto.chars().count() * (ANCHO + 1) * escala
}

/// Writes the text with its top left corner at (x, y)
pub fn escribir(fb: &mut Framebuffer, x: usize, y: usize, escala: usize, texto: &str, color: u32) {
    for (sombra, tono) in [(escala, 0x000000), (0, color)] {
        for (i, c) in texto.chars().enumerate() {
            let x0 = x + i * (ANCHO + 1) * escala + sombra;
            for (fila, bits) in glifo(c).iter().enumerate() {
                for col in 0..ANCHO {
                    if bits & (1 << (ANCHO - 1 - col)) == 0 {
                        continue;
                    }
                    let px = x0 + col * escala;
                    let py = y + fila * escala + sombra;
                    for dy in 0..escala {
                        for dx in 0..escala {
                            fb.set_pixel(px + dx, py + dy, tono);
                        }
                    }
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn cada_letra_usa_solo_5_columnas() {
        for c in "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789:-.,/()+".chars() {
            assert!(glifo(c).iter().all(|fila| fila >> ANCHO == 0), "{c}");
            assert!(glifo(c).iter().any(|&fila| fila != 0), "{c} esta vacia");
        }
        assert!(glifo(' ').iter().all(|&fila| fila == 0));
    }

    #[test]
    fn escribe_la_letra_en_su_lugar_con_sombra() {
        let mut fb = Framebuffer::new(20, 20);
        escribir(&mut fb, 2, 3, 1, "I", 0xFFFFFF);

        // The I has a 3 pixel bar on top, in columns 1 to 3 of the glyph
        let pixel = |x: usize, y: usize| fb.buffer()[y * 20 + x];
        assert_eq!(pixel(3, 3), 0xFFFFFF);
        assert_eq!(pixel(5, 3), 0xFFFFFF);
        assert_eq!(pixel(2, 3), 0x000000);
        // The shadow is one pixel down and right, where the letter doesn't paint
        assert_eq!(pixel(6, 4), 0x000000);
        assert_eq!(ancho("II", 2), 24);
    }

    #[test]
    fn no_se_sale_de_la_imagen() {
        let mut fb = Framebuffer::new(10, 10);
        escribir(&mut fb, 8, 8, 3, "MINA", 0xFFFFFF);
    }
}
